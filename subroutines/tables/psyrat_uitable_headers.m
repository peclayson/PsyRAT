function names = psyrat_uitable_headers(names)
%Break long uitable column headers onto two lines for the screen.
%
%   names = psyrat_uitable_headers(names) returns the ColumnName list with a
%   '|' (the classic uitable's line break) inserted into every entry that has
%   a two-line form in the map below; every other entry comes back unchanged.
%   A cellstr comes back as a cellstr and a string array as a string array,
%   in the input's shape.
%
%   map = psyrat_uitable_headers() returns the map itself (a two-column cell
%   array: one-line display name, two-line form), for the tests.
%
%Why: the classic uitable cannot wrap a header, so a header wider than its
%column is cut with an ellipsis. A live GUI look (Item 12, 2026-09-17) found that on
%six of the nine fixed-width table windows ('SEM (dependabil...',
%'Max # of Tri...', four identical 'MeanTrials...'). Rather than widen the
%windows past a laptop display, the long headers are shown on two lines. Only
%the on-screen ColumnName goes through this function: the CSV and XLSX headers
%keep the one-line names (G104). The width guard,
%tests/TestUitableWidthSlack.m, measures every line against its column, so a
%new long header needs an entry here or a wider column.
%
%The observed DoD table shows its CSV variable names on screen; its entries
%below also make the four mean-trial columns readable ('Mean Trials' over
%'ERP n'), which were identical once cut.

% Copyright (C) 2016-2026 Peter E. Clayson
%
%     This program is free software: you can redistribute it and/or modify
%     it under the terms of the GNU General Public License as published by
%     the Free Software Foundation, either version 3 of the License, or
%     any later version.
%
%     This program is distributed in the hope that it will be useful,
%     but WITHOUT ANY WARRANTY; without even the implied warranty of
%     MERCHANTABILITY or FITNESS FOR A PARTICULAR PURPOSE. See the
%     GNU General Public License for more details.
%
%     You should have received a copy of the GNU General Public License
%     along with this program (gpl.txt). If not, see
%     <http://www.gnu.org/licenses/>.

map = { ...
    'SEM (dependability)',            'SEM|(dependability)'; ...
    'SEM (generalizability)',         'SEM|(generalizability)'; ...
    'ICC (dependability)',            'ICC|(dependability)'; ...
    'ICC (generalizability)',         'ICC|(generalizability)'; ...
    'Group SEM (dependability)',      'Group SEM|(dependability)'; ...
    'Group SEM (generalizability)',   'Group SEM|(generalizability)'; ...
    'Group ICC (dependability)',      'Group ICC|(dependability)'; ...
    'Group ICC (generalizability)',   'Group ICC|(generalizability)'; ...
    'Group Between Std Dev',          'Group Between|Std Dev'; ...
    'Group Within Std Dev',           'Group Within|Std Dev'; ...
    'Within Person (Error)',          'Within Person|(Error)'; ...
    'Between-Person Std Dev',         'Between-Person|Std Dev'; ...
    'BP Covariance Std Dev',          'BP Covariance|Std Dev'; ...
    'Between-Trial Std Dev',          'Between-Trial|Std Dev'; ...
    'BT Covariance Std Dev',          'BT Covariance|Std Dev'; ...
    'Error Covariance Std Dev',       'Error Covariance|Std Dev'; ...
    'Mean # of Trials',               'Mean|# of Trials'; ...
    'Med # of Trials',                'Med|# of Trials'; ...
    'Min # of Trials',                'Min|# of Trials'; ...
    'Max # of Trials',                'Max|# of Trials'; ...
    'Std Dev of Trials',              'Std Dev of|Trials'; ...
    'Mean # of Splits',               'Mean|# of Splits'; ...
    'Med # of Splits',                'Med|# of Splits'; ...
    'Min # of Splits',                'Min|# of Splits'; ...
    'Max # of Splits',                'Max|# of Splits'; ...
    'Std Dev of Splits',              'Std Dev of|Splits'; ...
    'Subject Level Dependability',    'Subject Level|Dependability'; ...
    'Subject Level Generalizability', 'Subject Level|Generalizability'; ...
    'n Included',                     'n|Included'; ...
    'n Excluded',                     'n|Excluded'; ...
    'n_Included',                     'n|Included'; ...
    'n_Excluded',                     'n|Excluded'; ...
    'MeanTrials_ERP_1',               'Mean Trials|ERP 1'; ...
    'MeanTrials_ERP_2',               'Mean Trials|ERP 2'; ...
    'MeanTrials_ERP_3',               'Mean Trials|ERP 3'; ...
    'MeanTrials_ERP_4',               'Mean Trials|ERP 4'};

%the zero-argument call hands the map to the tests
if nargin == 0
    names = map;
    return;
end

%work on a cellstr and hand back the input's own type and shape
wasstring = isstring(names);
list = cellstr(names);
for k = 1:numel(list)
    hit = strcmp(map(:,1), list{k});
    if any(hit)
        list{k} = map{hit, 2};
    end
end
if wasstring
    names = string(list);
else
    names = list;
end

end
