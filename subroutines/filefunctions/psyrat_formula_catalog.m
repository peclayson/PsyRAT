    'Implemented',...
    'Difference variants apply the conditional residual to psyrat_diffrel (cases 12/15/...)';...
    ...
    'dyn_diff_d','R&C','Dynamic/conditional difference (Rast & Clayson)','Conditional difference reliability','Absolute (D)',...
    'DiffD(z) = uni_diff / (uni_diff + abs_error_diff(z))',...
