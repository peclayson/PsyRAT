    'G(z) = bp^2 / (bp^2 + sigma_pi,e(z)^2 / n'')',...
    'psyrat_rel_dynrel',...
    'Reference (Show Usage); estimated via Specify Inputs',...
    'Implemented',...
    'Reliability as a function of standardized z; reuses psyrat_rel_sing per z';...
    ...
    'dyn_d','R&C','Dynamic/conditional (Rast & Clayson)','Conditional coefficient','Absolute (D)',...
    'D(z) = bp^2 / (bp^2 + (sigma_pi,e(z)^2 + sigma_i^2) / n'')',...
    'psyrat_rel_dynrel',...
    'Reference (Show Usage); estimated via Specify Inputs',...
    'Implemented',...
    'D adds the trial main effect sigma_i^2; G excludes it (as Rocha Table 2)';...
    ...
    'dyn_icc_rel','R&C','Dynamic/conditional (Rast & Clayson)','Conditional ICC','Relative',...
    'ICC_rel(z) = bp^2 / (bp^2 + sigma_pi,e(z)^2)',...
    'psyrat_rel_dynrel',...
    'Reference (Show Usage); estimated via Specify Inputs',...
    'Implemented',...
    'Single-observation conditional ICC (n''=1)';...
    ...
    'dyn_icc_abs','R&C','Dynamic/conditional (Rast & Clayson)','Conditional ICC','Absolute',...
    'ICC_abs(z) = bp^2 / (bp^2 + sigma_pi,e(z)^2 + sigma_i^2)',...
    'psyrat_rel_dynrel',...
    'Reference (Show Usage); estimated via Specify Inputs',...
    'Implemented',...
    'Single-observation conditional ICC (n''=1); absolute adds sigma_i^2';...
    ...
    'dyn_diff_g','R&C','Dynamic/conditional difference (Rast & Clayson)','Conditional difference reliability','Relative (G)',...
