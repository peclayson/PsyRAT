    %(which key on {2,3,6}) exclude these rows; the 'dynrel' filter keeps them.
    'dyn_sigma_z','R&C','Dynamic/conditional (Rast & Clayson)','Conditional residual SD','Scale model',...
    'sigma_pi,e(z) = exp(alpha + b_sigma . X(z))',...
    'psyrat_rel_dynrel',...
    'Reference (Show Usage); estimated via Specify Inputs',...
    'Implemented',...
