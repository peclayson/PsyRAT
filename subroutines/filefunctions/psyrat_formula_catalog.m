if ~isempty(varargin)
    if mod(length(varargin),2)
        error('varargin:incomplete',... %Error code and associated error
            strcat('WARNING: Inputs are incomplete \n\n',...
            'Make sure each variable input is paired with a value \n'));
    end
    
    ind = find(strcmpi('analysis',varargin),1);
    if ~isempty(ind)
        analysis = varargin{ind+1};
    end
end

if isstring(analysis)
    analysis = char(analysis);
end

rows = {...
    't2_global_d','2','One-facet (p x i)','Global coefficient','Absolute (D)',...
    'D = bp^2 / (bp^2 + wp^2 / n)',...
    'psyrat_rel_sing',...
    'Formula Guide -> Run Formula',...
    'Implemented',...
    'Table 2 one-facet absolute global coefficient';...
    ...
    't2_global_g','2','One-facet (p x i)','Global coefficient','Relative (G)',...
    'G = bp^2 / (bp^2 + sigma_pi,e^2 / n)',...
    'psyrat_rel_sing',...
    'Formula Guide -> Run Formula',...
    'Implemented',...
    'Uses optional item SD (i) to separate sigma_i^2 from wp^2';...
    ...
    't2_icc_rel','2','One-facet (p x i)','ICC','Relative',...
    'ICC_rel = bp^2 / (bp^2 + sigma_pi,e^2)',...
    'psyrat_rel_sing',...
    'Formula Guide -> Run Formula',...
    'Implemented',...
    'Relative ICC excludes sigma_i^2 when i is provided';...
    ...
    't2_icc_abs','2','One-facet (p x i)','ICC','Absolute',...
    'ICC_abs = bp^2 / (bp^2 + sigma_pi,e^2 + sigma_i^2)',...
    'psyrat_rel_sing',...
    'Formula Guide -> Run Formula',...
    'Implemented',...
    'Absolute ICC maps to bp^2 / (bp^2 + wp^2)';...
    ...
    't2_cut_d','2','One-facet (p x i)','Cut-score coefficient','Absolute (D)',...
    'CutD = (bp^2 + (mu-cut)^2) / (bp^2 + (mu-cut)^2 + err_abs)',...
    'psyrat_cutscore_sing',...
    'Formula Guide -> Run Formula',...
    'Implemented',...
    'Criterion is entered as cut';...
    ...
    't3_rel_d','3','Two-facet (p x i x o)','CE/CS/CES coefficient','Absolute (D)',...
    'D = universe / (universe + abs_error)',...
    'psyrat_rel_trt',...
    'TRT startview + Formula Guide -> Run Formula',...
    'Implemented',...
    'reltype selects CE/CS/CES';...
    ...
    't3_rel_g','3','Two-facet (p x i x o)','CE/CS/CES coefficient','Relative (G)',...
    'G = universe / (universe + rel_error)',...
    'psyrat_rel_trt',...
    'TRT startview + Formula Guide -> Run Formula',...
    'Implemented',...
    'reltype selects CE/CS/CES';...
    ...
    't3_icc_abs','3','Two-facet (p x i x o)','ICC (CE/CS/CES)','Absolute',...
    'ICC = universe / (universe + abs_error) at obs=1, nocc=1',...
    'psyrat_rel_trt (obs=1,nocc=1)',...
    'Formula Guide -> Run Formula',...
    'Implemented',...
    'Uses reltype and absolute error';...
    ...
    't3_icc_rel','3','Two-facet (p x i x o)','ICC (CE/CS/CES)','Relative',...
    'ICC = universe / (universe + rel_error) at obs=1, nocc=1',...
    'psyrat_rel_trt (obs=1,nocc=1)',...
    'Formula Guide -> Run Formula',...
    'Implemented',...
    'Uses reltype and relative error';...
    ...
    't3_cut_d','3','Two-facet (p x i x o)','Cut-score coefficient','Absolute (D)',...
    'Cut = (universe + (mu-cut)^2) / (universe + (mu-cut)^2 + abs_error)',...
    'psyrat_cutscore_trt',...
    'Formula Guide -> Run Formula',...
    'Implemented',...
    'Supports reltype and criterion (cut)';...
    ...
    't6_diff1_d','6','Difference score one-facet','Difference reliability','Absolute (D)',...
    'DiffD = uni_diff / (uni_diff + abs_error_diff)',...
    'psyrat_diffrel',...
    'Sing diff startview + Formula Guide -> Run Formula',...
    'Implemented',...
    'Supports optional residual covariance for concurrent measures';...
    ...
    't6_diff1_g','6','Difference score one-facet','Difference reliability','Relative (G)',...
    'DiffG = uni_diff / (uni_diff + rel_error_diff)',...
    'psyrat_diffrel',...
    'Sing diff startview + Formula Guide -> Run Formula',...
    'Implemented',...
    'Absolute/relative set by est';...
    ...
    't6_diff2_d','6','Difference score two-facet','Difference reliability CE/CS/CES','Absolute (D)',...
    'Diff = uni_diff / (uni_diff + abs_error_diff)',...
    'psyrat_diffrel_trt',...
    'Formula Guide -> Run Formula',...
    'Implemented',...
    'Uses reltype and supports residual covariance';...
    ...
    't6_diff2_g','6','Difference score two-facet','Difference reliability CE/CS/CES','Relative (G)',...
    'Diff = uni_diff / (uni_diff + rel_error_diff)',...
    'psyrat_diffrel_trt',...
    'Formula Guide -> Run Formula',...
    'Implemented',...
    'Uses reltype and supports residual covariance';...
    ...
    %--- Dynamic/conditional reliability (Rast & Clayson in press, analyses 11-22).
