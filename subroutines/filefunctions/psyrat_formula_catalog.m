    'Reference (Show Usage); estimated via Specify Inputs',...
    'Implemented',...
    'Absolute adds the difference trial (and, with occasions, occasion) error terms';...
    ...
    'dyn_rescor','R&C','Dynamic/conditional difference (Rast & Clayson)','Residual correlation','Covariance',...
