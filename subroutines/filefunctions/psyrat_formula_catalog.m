    'PIT-transformed residuals - a different estimand, hence the distinct symbol. Per-subject '...
    'rho adds the between-person SD'];...
    ...
    %--- Nonparallel splits, observed design (Rocha Tables 4/5; analyses 23/24).
    %paper_table tokens '4'/'5' keep these out of the Rocha sing/trt filters
    %(which key on {2}/{3}/{6}); the 'splits' filter keeps them. Estimated
    %data-driven via Specify Inputs (the n_i/weight column + Nonparallel). The
    %parallel splits path (splits=2) reuses the Table 2/3 rows above unchanged.
    't4_d','4','Splits one-facet p x (i:s)','Global coefficient','Absolute (D)',...
    'D = sig_p^2 / (sig_p^2 + sig_ps^2/ns + sig_s^2/ns + sig_err^2/(ns*nbar_i))',...
    'psyrat_splits_summary',...
    'Splits startview + Specify Inputs (n_i column, Nonparallel)',...
    'Implemented',...
    'Exact; reuses psyrat_rel_sing with SD-scaled residual (nbar_i = harmonic mean of n_i); observed design only';...
    ...
