    ...
    't4_sem','4','Splits one-facet p x (i:s)','SEM','Absolute & Relative',...
    'SEM_abs = sqrt((sig_ps^2 + sig_s^2 + sig_err^2/nbar_i)/ns); SEM_rel drops sig_s^2',...
