%Optional input
% analysis - 'all' (default), 'sing', 'sing_diff', 'sing_sserr', 'trt',
%            'dynrel' (dynamic/conditional reliability, Rast & Clayson), or
%            'splits' (nonparallel splits observed design, Rocha Tables 4/5)

