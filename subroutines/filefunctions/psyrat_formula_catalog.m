    'SEM = sqrt(error term per reltype); err = sqrt(sig_pos^2 + sig_err^2/nbar_i)',...
    'psyrat_splits_summary',...
    'Splits startview + Specify Inputs (n_i column, Nonparallel)',...
    'Implemented',...
    'Absolute SEM exact; relative SEM is an upper bound';...
    };

catalog = cell2table(rows,...
    'VariableNames',...
    {'formula_id','paper_table','design','coefficient','decision_type','formula_ascii',...
    'psyrat_function','gui_status','implementation_status','notes'});

switch lower(analysis)
    case {'sing','sing_sserr'}
        onefacet = ~cellfun(@isempty,strfind(lower(catalog.design),'one-facet'));
        keep = ismember(catalog.paper_table,{'2'}) | ...
            (strcmp(catalog.paper_table,'6') & onefacet);
        catalog = catalog(keep,:);
    case 'sing_diff'
        onefacet = ~cellfun(@isempty,strfind(lower(catalog.design),'one-facet'));
        keep = ismember(catalog.paper_table,{'2'}) | ...
            (strcmp(catalog.paper_table,'6') & onefacet);
        catalog = catalog(keep,:);
    case 'trt'
        twofacet = ~cellfun(@isempty,strfind(lower(catalog.design),'two-facet'));
        keep = ismember(catalog.paper_table,{'3'}) | ...
            (strcmp(catalog.paper_table,'6') & twofacet);
        catalog = catalog(keep,:);
    case 'dynrel'
        %dynamic/conditional reliability (Rast & Clayson); tagged paper_table 'R&C'
        keep = strcmp(catalog.paper_table,'R&C');
        catalog = catalog(keep,:);
    case 'splits'
        %nonparallel splits, observed design (Rocha Tables 4/5); tagged '4'/'5'
        keep = ismember(catalog.paper_table,{'4','5'});
        catalog = catalog(keep,:);
    case 'all'
        %no filtering
    otherwise
        error('varargin:analysis',... %Error code and associated error
            strcat('WARNING: analysis is invalid. Valid values are\n',...
            '''all'', ''sing'', ''sing_sserr'', ''sing_diff'', ''trt'', ''dynrel'', or ''splits''.\n'));
end

end
