function m = localCovmat(v1,v2,cv)
n = length(v1);
m = zeros(n,2,2);
m(:,1,1) = v1(:);
m(:,2,2) = v2(:);
m(:,2,1) = cv(:);
m(:,1,2) = cv(:);
end

function C = localCorr4(R, nd)
% Replicate one literal 4x4 correlation matrix across nd draws.
C = zeros(nd,4,4);
for d = 1:nd
    C(d,:,:) = R;
end
end
